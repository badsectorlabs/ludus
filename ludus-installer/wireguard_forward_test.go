func TestWireGuardForwardUsesManagementAddressAndImportedPort(t *testing.T) {
	opts := Options{IP: "10.40.1.20/24", NATIP: "192.0.2.253", WireGuardPort: 51820}
	if err := applyImportedEndpoints([]byte("wireguard_port: 51999\n"), &opts); err != nil {
		t.Fatal(err)
	}
	plan, err := wireGuardForwardPlan(&opts)
	if err != nil || plan.Address.String() != "10.40.1.20" || plan.Port != 51999 {
		t.Fatalf("management/import selection lost: %+v %v", plan, err)
	}
	for _, ip := range []string{"", "dhcp", "10.40.1.20", "0.0.0.0/24", "::/64", "127.0.0.1/8", "ff02::1/64"} {
		opts.IP = ip
		if _, err := wireGuardForwardPlan(&opts); err == nil {
			t.Fatalf("accepted unsafe static address %q", ip)
		}
	}
	opts.NoWireGuardForward = true
	if err := installWireGuardForward(context.Background(), &opts); err != nil {
		t.Fatalf("opt-out performed host installation: %v", err)
	}
	t.Setenv("PATH", t.TempDir())
	for _, migrating := range []bool{true, false} {
		if err := ensureHostDependencies(context.Background(), &opts, migrating); err != nil {
			t.Fatalf("opt-out required host packages (migration=%v): %v", migrating, err)
		}
	}
}

func TestWireGuardForwardRulesAreUDPOnlyAndHostScoped(t *testing.T) {
	for _, cidr := range []string{"10.40.1.20/24", "2001:db8:40::20/64"} {
		plan, err := wireGuardForwardPlan(&Options{IP: cidr, WireGuardPort: 51999})
		if err != nil {
			t.Fatal(err)
		}
		wantBinary, wantFile := "iptables", wireGuardRulesV4
		wantDestination := "10.40.1.20:51999"
		if strings.Contains(cidr, ":") {
			wantBinary, wantFile, wantDestination = "ip6tables", wireGuardRulesV6, "[2001:db8:40::20]:51999"
		}
		if binary, file, _ := plan.firewall(); binary != wantBinary || file != wantFile {
			t.Fatal("wrong address-family firewall")
		}
		nat, snat, incoming, reply := 0, false, false, false
		for _, rule := range plan.rules() {
			args := strings.Join(rule.Args, " ")
			if !strings.Contains(args, "--comment "+wireGuardComment) || !strings.Contains(args, "-p udp") || !strings.Contains(args, "51999") {
				t.Fatalf("unowned or non-UDP/port-scoped rule: %s", args)
			}
			if strings.Contains(args, "-j DNAT") {
				nat++
				if !strings.Contains(args, "--dst-type LOCAL") || !strings.Contains(args, "--to-destination "+wantDestination) {
					t.Fatalf("DNAT hijacks transit or targets wrong address: %s", args)
				}
			} else if !strings.Contains(args, "--ctstate DNAT") || !strings.Contains(args, "--ctorigdstport 51999") {
				t.Fatalf("rule changes direct guest traffic: %s", args)
			}
			snat = snat || rule.Chain == "POSTROUTING" && strings.Contains(args, "-j MASQUERADE")
			incoming = incoming || rule.Chain == "FORWARD" && strings.Contains(args, "--ctdir ORIGINAL")
			reply = reply || rule.Chain == "FORWARD" && strings.Contains(args, "--ctdir REPLY")
		}
		if nat != 2 || !snat || !incoming || !reply {
			t.Fatal("missing local/remote NAT or same-subnet return path")
		}
	}
}

func TestWireGuardPersistentRulesReplaceOnlyLudusRules(t *testing.T) {
	plan, err := wireGuardForwardPlan(&Options{IP: "10.40.1.20/24", WireGuardPort: 51820})
	if err != nil {
		t.Fatal(err)
	}
	// A host file without a nat table, an operator DROP rule, and a stale
	// forward to a previous container saved by iptables-save.
	existing := "# Generated by iptables-save\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD DROP [0:0]\n:OUTPUT ACCEPT [0:0]\n" +
		"-A FORWARD -d 10.9.9.9/32 -p udp -m udp --dport 51820 -m comment --comment ludus-wireguard -j ACCEPT\n" +
		"-A FORWARD -i vmbr9 -j DROP\nCOMMIT\n# Completed\n"
	merged := string(mergeWireGuardRules([]byte(existing), plan.rules()))
	if strings.Contains(merged, "10.9.9.9") {
		t.Fatal("stale Ludus forward was persisted")
	}
	if !strings.Contains(merged, ":FORWARD DROP [0:0]\n") || !strings.Contains(merged, "-A FORWARD -i vmbr9 -j DROP\nCOMMIT\n# Completed\n") {
		t.Fatalf("operator rules or policies changed:\n%s", merged)
	}
	if !strings.HasPrefix(merged, "# Generated by iptables-save\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD DROP [0:0]\n:OUTPUT ACCEPT [0:0]\n-A FORWARD -m comment --comment ludus-wireguard ") {
		t.Fatalf("forward does not precede the operator DROP rule:\n%s", merged)
	}
	if !strings.HasSuffix(merged, "COMMIT\n# Completed\n*nat\n"+
		"-A PREROUTING "+strings.Join(plan.rules()[0].Args, " ")+"\n"+
		"-A OUTPUT "+strings.Join(plan.rules()[1].Args, " ")+"\n"+
		"-A POSTROUTING "+strings.Join(plan.rules()[2].Args, " ")+"\nCOMMIT\n") {
		t.Fatalf("missing nat table was not created:\n%s", merged)
	}
	if strings.Count(merged, wireGuardComment) != len(plan.rules()) {
		t.Fatalf("wrong number of Ludus rules:\n%s", merged)
	}
	if again := string(mergeWireGuardRules([]byte(merged), plan.rules())); again != merged {
		t.Fatalf("rerunning the installer changed the persisted rules:\n%s", again)
	}
	if fresh := string(mergeWireGuardRules(nil, plan.rules())); !strings.HasPrefix(fresh, "*nat\n") || strings.Count(fresh, "COMMIT\n") != 2 {
		t.Fatalf("missing rules file not created:\n%s", fresh)
	}
}

func TestMigrationWireGuardOptOutPreservesAPIAndJournal(t *testing.T) {
	c := migrationNetworkPlan{Bridge: "ludusmg", IP: "172.31.255.2/30", Uplink: "vmbr0", Port: 8080, AdminPort: 8081, ExposeAdminPort: true, WireGuardPort: 51820, NoWireGuardForward: true}
	data, err := json.Marshal(Migration{Options: &Options{TokenSecret: "never-save-options"}, Network: c})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), "never-save-options") {
		t.Fatal("journal serialized Options")
	}
	var saved Migration
	if err := json.Unmarshal(data, &saved); err != nil || !saved.Network.NoWireGuardForward {
		t.Fatalf("forwarding opt-out was lost on restart: %v", err)
	}
	for _, mode := range []string{"stage", "wireguard", "start"} {
		api, admin := false, false
		for _, rule := range migrationForwardRules(saved.Network, mode, "owner") {
			args := strings.Join(rule.Args, " ")
			if strings.Contains(args, "-p udp") {
				t.Fatalf("opted-out migration still forwards UDP: %s", args)
			}
			api = api || strings.Contains(args, "-p tcp --dport 8080 -j DNAT")
			admin = admin || strings.Contains(args, "-p tcp --dport 8081 -j DNAT")
		}
		if (mode == "start") != (api && admin) {
			t.Fatalf("opt-out changed API handoff for mode %s", mode)
		}
	}
	t.Setenv("PATH", t.TempDir())
	saved.Network.HostAddresses = []string{"192.0.2.1"}
	if err := saved.resetWireGuardSessions(context.Background()); err != nil {
		t.Fatalf("opted-out migration executed conntrack: %v", err)
	}
	var legacy migrationNetworkPlan
	if err := json.Unmarshal([]byte(`{"wireguard_port":51820}`), &legacy); err != nil || legacy.NoWireGuardForward {
		t.Fatal("old journal no longer defaults to forwarding")
	}
}
